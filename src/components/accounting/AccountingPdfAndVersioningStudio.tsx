import React, { useMemo, useState } from 'react';
import {
  CheckCircle2,
  Download,
  Eye,
  FileText,
  GitCompare,
  History,
  Image as ImageIcon,
  Palette,
  Printer,
  RotateCcw,
  Save,
  Sparkles,
} from 'lucide-react';
import { useERP } from '../../context/ERPContext';
import {
  ACCOUNTING_PDF_TEMPLATES,
  AccountingDocumentVersion,
  AccountingDocumentVersionPayload,
  AccountingPdfBrandingOptions,
  AccountingPdfDocumentType,
  AccountingPdfTemplateId,
  compareDocumentVersions,
  createDocumentVersionSnapshot,
  downloadAccountingPdfHtmlSnapshot,
  generateAccountingPdfDocument,
  printAccountingPdfHtml,
  restoreDocumentVersionPayload,
} from '../../core/accountingPdfService';

export interface AccountingPdfAndVersioningStudioProps {
  initialMode?: 'PDF_STUDIO' | 'VERSIONING';
}

export const AccountingPdfAndVersioningStudio: React.FC<
  AccountingPdfAndVersioningStudioProps
> = ({ initialMode = 'PDF_STUDIO' }) => {
  const {
    chartAccounts: accounts,
    salesInvoices,
    journalEntries,
    company: companyInfo,
    currency,
    language,
    currentAccount,
    dispatchToastAndPushNotification,
  } = useERP();

  const isAr = language === 'ar';

  const notify = (msg: string, severity: 'INFO' | 'SUCCESS' | 'WARNING' | 'CRITICAL' = 'SUCCESS') => {
    dispatchToastAndPushNotification({
      titleAr: 'استوديو المستندات المحاسبية',
      titleEn: 'Accounting Document Studio',
      messageAr: msg,
      messageEn: msg,
      severity: severity.toLowerCase() as 'info' | 'success' | 'warning' | 'critical',
      category: 'LIVE_EVENTS',
    });
  };

  const [studioTab, setStudioTab] = useState<'PDF_STUDIO' | 'VERSIONING'>(initialMode);
  const [documentType, setDocumentType] = useState<AccountingPdfDocumentType>('SALES_INVOICE');
  const [selectedInvoiceId, setSelectedInvoiceId] = useState<string>(
    salesInvoices[0]?.id || 'inv-default'
  );
  const [selectedJournalId, setSelectedJournalId] = useState<string>(
    journalEntries[0]?.id || 'je-default'
  );

  const [branding, setBranding] = useState<AccountingPdfBrandingOptions>({
    templateId: 'CORPORATE_STANDARD',
    primaryColor: '#1e3a8a',
    accentColor: '#2563eb',
    showLogo: true,
    customLogoDataUrl: companyInfo.logo || companyInfo.logoUrl || '',
    companyNameOverride: companyInfo.name || '',
    taxNumberOverride: companyInfo.taxNumber || '',
    headerNote: isAr
      ? 'مستند مالي رسمي معتمد ومطابق لمعايير الفوترة الضريبية'
      : 'Certified Official Financial Document',
    bodyTermsNote: isAr
      ? 'يستحق السداد خلال 30 يوماً من تاريخ الإصدار. تخضع جميع البنود لضريبة القيمة المضافة.'
      : 'Payment due within 30 days of issue. Subject to standard VAT regulations.',
    bankDetailsNote: 'IBAN: SA4420000001234567891234 · Al-Rajhi Corporate Bank',
    footerNote: isAr
      ? 'تم إصدار هذا المستند آلياً من نظام الإدارة المالية المتكامل ويعتبر معتمداً بدون توقيع خطي.'
      : 'Electronically generated by RLM Enterprise Accounting Engine.',
    watermarkText: 'CERTIFIED ORIGINAL',
    includeSignatureBlock: true,
    includeQrCode: true,
    paperSize: 'A4',
    language,
  });

  // Document Versioning State (Seeded with initial v1 & v2 history so comparison works immediately)
  const [versions, setVersions] = useState<AccountingDocumentVersion[]>(() => {
    const firstInv = salesInvoices[0];
    const docId = firstInv ? `DOC-${firstInv.invoiceNumber}` : 'DOC-INV-1001';
    const refNum = firstInv?.invoiceNumber || 'INV-2025-1001';
    const cust = firstInv?.customerName || 'شركة الآفاق للتجارة والمقاولات';
    const baseSubtotal = Number(firstInv?.subtotal) || 10000;
    const baseTax = Number(firstInv?.taxAmount) || 1500;
    const baseGrand = Number(firstInv?.grandTotal) || 11500;

    const v1Payload: AccountingDocumentVersionPayload = {
      documentType: 'SALES_INVOICE',
      referenceId: firstInv?.id || 'inv-1',
      referenceNumber: refNum,
      customerOrTitle: cust,
      date: firstInv?.date?.slice(0, 10) || '2025-05-01',
      status: 'DRAFT',
      subtotal: Math.round(baseSubtotal * 0.9),
      discountAmount: 0,
      taxAmount: Math.round(baseTax * 0.9),
      grandTotal: Math.round(baseGrand * 0.9),
      notes: 'النسخة الأولية قبل مراجعة التسعير والخصم التجاري',
      brandingTemplateId: 'CORPORATE_STANDARD',
      lineItemsSummary: [
        {
          code: 'SKU-101',
          label: 'توريد تجهيزات ومعدات مستودعات',
          qtyOrDebit: 2,
          priceOrCredit: Math.round((baseSubtotal * 0.9) / 2),
          total: Math.round(baseSubtotal * 0.9),
        },
      ],
    };

    const v1 = createDocumentVersionSnapshot({
      documentId: docId,
      existingVersions: [],
      payload: v1Payload,
      createdBy: 'أحمد المحاسب (Accountant)',
      changeReason: 'إصدار المسودة الأولية للفاتورة (Initial v1 Draft)',
      nowIso: '2025-05-01T09:15:00.000Z',
    });

    const v2Payload: AccountingDocumentVersionPayload = {
      ...v1Payload,
      status: 'POSTED',
      subtotal: baseSubtotal,
      discountAmount: 250,
      taxAmount: baseTax,
      grandTotal: baseGrand,
      notes: 'تم اعتماد الأسعار النهائية وإضافة بند التركيب والضمان السنوي',
      brandingTemplateId: 'ZATCA_TAX_COMPLIANT',
      lineItemsSummary: [
        {
          code: 'SKU-101',
          label: 'توريد تجهيزات ومعدات مستودعات',
          qtyOrDebit: 2,
          priceOrCredit: Math.round(baseSubtotal * 0.4),
          total: Math.round(baseSubtotal * 0.8),
        },
        {
          code: 'SRV-202',
          label: 'عقد صيانة ومعايرة سنوي',
          qtyOrDebit: 1,
          priceOrCredit: Math.round(baseSubtotal * 0.2),
          total: Math.round(baseSubtotal * 0.2),
        },
      ],
    };

    const v2 = createDocumentVersionSnapshot({
      documentId: docId,
      existingVersions: [v1],
      payload: v2Payload,
      createdBy: 'المدير المالي (CFO)',
      changeReason: 'تعديل البنود واعتماد الفاتورة الضريبية (v2 Approved)',
      nowIso: '2025-05-02T14:30:00.000Z',
    });

    // Also seed a Financial Report version pair (Trial Balance)
    const tbDocId = 'DOC-REPORT-TRIAL-BALANCE';
    const tbV1 = createDocumentVersionSnapshot({
      documentId: tbDocId,
      existingVersions: [],
      payload: {
        documentType: 'TRIAL_BALANCE',
        referenceId: 'tb-2025-q1',
        referenceNumber: 'TB-2025-Q1',
        customerOrTitle: 'ميزان المراجعة الربع سنوي (قبل التسويات الجردية)',
        date: '2025-03-31',
        status: 'PRE_AUDIT',
        subtotal: 420000,
        discountAmount: 0,
        taxAmount: 0,
        grandTotal: 420000,
        notes: 'قبل إثبات قيد الإهلاك الشهري وتسوية العهد',
        brandingTemplateId: 'MINIMAL_AUDIT',
        lineItemsSummary: [
          { code: '1101', label: 'النقدية والبنوك', qtyOrDebit: 185000, priceOrCredit: 0, total: 185000 },
          { code: '4101', label: 'إيرادات المبيعات', qtyOrDebit: 0, priceOrCredit: 235000, total: 235000 },
        ],
      },
      createdBy: 'مدقق الحسابات',
      changeReason: 'نسخة ما قبل التسويات الجردية',
      nowIso: '2025-03-31T16:00:00.000Z',
    });

    const tbV2 = createDocumentVersionSnapshot({
      documentId: tbDocId,
      existingVersions: [tbV1],
      payload: {
        documentType: 'TRIAL_BALANCE',
        referenceId: 'tb-2025-q1',
        referenceNumber: 'TB-2025-Q1',
        customerOrTitle: 'ميزان المراجعة الربع سنوي (بعد التسويات النهائية)',
        date: '2025-04-02',
        status: 'AUDITED_FINAL',
        subtotal: 448500,
        discountAmount: 0,
        taxAmount: 0,
        grandTotal: 448500,
        notes: 'شامل قيد إهلاك الأصول الثابتة ومخصص الديون المشكوك فيها',
        brandingTemplateId: 'ROYAL_LEDGER',
        lineItemsSummary: [
          { code: '1101', label: 'النقدية والبنوك', qtyOrDebit: 185000, priceOrCredit: 0, total: 185000 },
          { code: '4101', label: 'إيرادات المبيعات', qtyOrDebit: 0, priceOrCredit: 235000, total: 235000 },
          { code: '5204', label: 'مصروف إهلاك الأصول', qtyOrDebit: 28500, priceOrCredit: 0, total: 28500 },
        ],
      },
      createdBy: 'المدير المالي (CFO)',
      changeReason: 'إغلاق الفترة المحاسبية بعد المراجعة',
      nowIso: '2025-04-02T11:20:00.000Z',
    });

    return [v2, v1, tbV2, tbV1];
  });

  const [selectedBaseVersionId, setSelectedBaseVersionId] = useState<string>(
    () => versions[1]?.versionId || ''
  );
  const [selectedTargetVersionId, setSelectedTargetVersionId] = useState<string>(
    () => versions[0]?.versionId || ''
  );
  const [changeReasonInput, setChangeReasonInput] = useState<string>('');
  const [restoredBannerText, setRestoredBannerText] = useState<string>('');

  const selectedInvoice = useMemo(
    () => salesInvoices.find((i) => i.id === selectedInvoiceId) || salesInvoices[0] || null,
    [salesInvoices, selectedInvoiceId]
  );

  const selectedJournal = useMemo(
    () => journalEntries.find((j) => j.id === selectedJournalId) || journalEntries[0] || null,
    [journalEntries, selectedJournalId]
  );

  const currentDocId = useMemo(() => {
    if (documentType === 'SALES_INVOICE') {
      return `DOC-${selectedInvoice?.invoiceNumber || 'INV-1001'}`;
    }
    return `DOC-REPORT-${documentType}`;
  }, [documentType, selectedInvoice]);

  const currentDocVersionCount = useMemo(
    () => versions.filter((v) => v.documentId === currentDocId).length + 1,
    [versions, currentDocId]
  );

  const generatedPdf = useMemo(
    () =>
      generateAccountingPdfDocument({
        documentType,
        companyInfo,
        currency,
        branding: { ...branding, language },
        invoice: selectedInvoice,
        journalEntry: selectedJournal,
        accounts,
        versionNumber: currentDocVersionCount,
      }),
    [
      documentType,
      companyInfo,
      currency,
      branding,
      language,
      selectedInvoice,
      selectedJournal,
      accounts,
      currentDocVersionCount,
    ]
  );

  const comparisonResult = useMemo(() => {
    const baseVer = versions.find((v) => v.versionId === selectedBaseVersionId) || versions[1] || versions[0];
    const targetVer =
      versions.find((v) => v.versionId === selectedTargetVersionId) || versions[0];
    if (!baseVer || !targetVer) return null;
    return compareDocumentVersions(baseVer, targetVer);
  }, [versions, selectedBaseVersionId, selectedTargetVersionId]);

  const handleTemplateSelect = (templateId: AccountingPdfTemplateId) => {
    const tpl = ACCOUNTING_PDF_TEMPLATES.find((t) => t.id === templateId);
    setBranding((prev) => ({
      ...prev,
      templateId,
      primaryColor: tpl?.defaultPrimary || prev.primaryColor,
      accentColor: tpl?.defaultAccent || prev.accentColor,
    }));
  };

  const handleLogoUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    const reader = new FileReader();
    reader.onload = () => {
      if (typeof reader.result === 'string') {
        setBranding((prev) => ({
          ...prev,
          showLogo: true,
          customLogoDataUrl: reader.result as string,
        }));
      }
    };
    reader.readAsDataURL(file);
  };

  const handleSaveNewVersionSnapshot = () => {
    const payload: AccountingDocumentVersionPayload =
      documentType === 'SALES_INVOICE' && selectedInvoice
        ? {
            documentType: 'SALES_INVOICE',
            referenceId: selectedInvoice.id,
            referenceNumber: selectedInvoice.invoiceNumber,
            customerOrTitle: selectedInvoice.customerName,
            date: String(selectedInvoice.date).slice(0, 10),
            status: selectedInvoice.status,
            subtotal: Number(selectedInvoice.subtotal) || 0,
            discountAmount: Number(selectedInvoice.discountAmount) || 0,
            taxAmount: Number(selectedInvoice.taxAmount) || 0,
            grandTotal: Number(selectedInvoice.grandTotal) || 0,
            notes: `${branding.headerNote || ''} | ${branding.bodyTermsNote || ''}`.trim(),
            brandingTemplateId: branding.templateId,
            lineItemsSummary: (selectedInvoice.items || []).map((it) => ({
              code: it.sku || it.productId,
              label: it.productName,
              qtyOrDebit: Number(it.quantity) || 1,
              priceOrCredit: Number(it.unitPrice) || 0,
              total: Number(it.total) || 0,
            })),
          }
        : {
            documentType,
            referenceId: generatedPdf.id,
            referenceNumber: generatedPdf.referenceNumber,
            customerOrTitle: isAr ? generatedPdf.titleAr : generatedPdf.titleEn,
            date: new Date().toISOString().slice(0, 10),
            status: 'CERTIFIED',
            subtotal: generatedPdf.totalAmount,
            discountAmount: 0,
            taxAmount: 0,
            grandTotal: generatedPdf.totalAmount,
            notes: `${branding.headerNote || ''} | ${branding.bodyTermsNote || ''}`.trim(),
            brandingTemplateId: branding.templateId,
            lineItemsSummary: accounts.slice(0, 5).map((a) => ({
              code: a.code,
              label: a.nameAr,
              qtyOrDebit: Math.max(0, Number(a.balance) || 0),
              priceOrCredit: 0,
              total: Math.abs(Number(a.balance) || 0),
            })),
          };

    const newVer = createDocumentVersionSnapshot({
      documentId: currentDocId,
      existingVersions: versions,
      payload,
      createdBy: currentAccount?.nameAr || currentAccount?.name || 'المحاسب الرئيسي',
      changeReason:
        changeReasonInput.trim() ||
        (isAr ? 'حفظ نسخة معتمدة من استوديو PDF' : 'Saved snapshot from PDF Studio'),
    });

    setVersions((prev) => [newVer, ...prev]);
    setSelectedTargetVersionId(newVer.versionId);
    if (versions[0]) {
      setSelectedBaseVersionId(versions[0].versionId);
    }
    setChangeReasonInput('');

    notify(
      isAr
        ? `تم حفظ الإصدار رقم v${newVer.versionNumber} للمستند ${newVer.payload.referenceNumber} بنجاح`
        : `Saved version v${newVer.versionNumber} for ${newVer.payload.referenceNumber}`,
      'SUCCESS'
    );
  };

  const handleRestoreVersion = (ver: AccountingDocumentVersion) => {
    const { restoredPayload, auditVersionSnapshot } = restoreDocumentVersionPayload({
      versionToRestore: ver,
      existingVersions: versions,
      restoredBy: currentAccount?.nameAr || currentAccount?.name || 'مدير الحسابات',
    });

    setVersions((prev) => [auditVersionSnapshot, ...prev]);
    setSelectedTargetVersionId(auditVersionSnapshot.versionId);
    setSelectedBaseVersionId(ver.versionId);

    // Apply restored branding template & notes immediately
    handleTemplateSelect(restoredPayload.brandingTemplateId);
    setBranding((prev) => ({
      ...prev,
      bodyTermsNote: restoredPayload.notes,
    }));

    const msg = isAr
      ? `تمت استعادة الإصدار v${ver.versionNumber} (${ver.payload.referenceNumber}) وتسجيل قيد استعادة رقم v${auditVersionSnapshot.versionNumber}`
      : `Restored version v${ver.versionNumber} (${ver.payload.referenceNumber}) as new active snapshot v${auditVersionSnapshot.versionNumber}`;
    setRestoredBannerText(msg);

    notify(msg, 'SUCCESS');
  };

  return (
    <div
      data-testid="accounting-pdf-and-versioning-studio"
      className="space-y-4"
    >
      {/* Mode Switcher Bar */}
      <div className="flex flex-wrap items-center justify-between gap-3 bg-white dark:bg-slate-900 p-3.5 rounded-2xl border border-slate-200/80 dark:border-slate-800">
        <div className="flex items-center gap-2">
          <div className="p-2 rounded-xl bg-blue-600/10 text-blue-600 dark:text-blue-400">
            <FileText className="w-5 h-5" />
          </div>
          <div>
            <h3 className="text-sm sm:text-base font-bold text-slate-900 dark:text-slate-100">
              {isAr
                ? 'استوديو قوالب PDF الاحترافية ونظام إصدارات المستندات المالية'
                : 'Accounting PDF Template Studio & Document Versioning System'}
            </h3>
            <p className="text-xs text-slate-500 dark:text-slate-400">
              {isAr
                ? 'تصميم وطباعة الفواتير والتقارير المالية مع الهوية البصرية، وحفظ ومقارنة واستعادة الإصدارات السابقة'
                : 'Generate branded PDF invoices/reports and view, compare, and restore historical document versions'}
            </p>
          </div>
        </div>

        <div className="inline-flex items-center gap-1.5 p-1 bg-slate-100 dark:bg-slate-800 rounded-xl">
          <button
            type="button"
            data-testid="studio-switch-pdf"
            onClick={() => setStudioTab('PDF_STUDIO')}
            className={`flex items-center gap-1.5 px-3.5 py-2 rounded-lg text-xs font-bold transition cursor-pointer ${
              studioTab === 'PDF_STUDIO'
                ? 'bg-blue-600 text-white shadow-xs'
                : 'text-slate-600 dark:text-slate-300 hover:bg-white/60 dark:hover:bg-slate-700'
            }`}
          >
            <Printer className="w-3.5 h-3.5" />
            <span>{isAr ? 'استوديو قوالب PDF والطباعة' : 'PDF Templates & Branding'}</span>
          </button>

          <button
            type="button"
            data-testid="studio-switch-versioning"
            onClick={() => setStudioTab('VERSIONING')}
            className={`flex items-center gap-1.5 px-3.5 py-2 rounded-lg text-xs font-bold transition cursor-pointer ${
              studioTab === 'VERSIONING'
                ? 'bg-blue-600 text-white shadow-xs'
                : 'text-slate-600 dark:text-slate-300 hover:bg-white/60 dark:hover:bg-slate-700'
            }`}
          >
            <History className="w-3.5 h-3.5" />
            <span>
              {isAr
                ? `إصدارات المستندات والمقارنة (${versions.length})`
                : `Document Versioning (${versions.length})`}
            </span>
          </button>
        </div>
      </div>

      {restoredBannerText && (
        <div
          data-testid="version-restored-banner"
          className="flex items-center justify-between gap-3 px-4 py-3 rounded-xl bg-emerald-50 dark:bg-emerald-950/40 border border-emerald-300 dark:border-emerald-700 text-emerald-900 dark:text-emerald-200 text-xs font-bold"
        >
          <div className="flex items-center gap-2">
            <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0" />
            <span>{restoredBannerText}</span>
          </div>
          <button
            type="button"
            onClick={() => setRestoredBannerText('')}
            className="text-[11px] underline cursor-pointer"
          >
            {isAr ? 'إغلاق' : 'Dismiss'}
          </button>
        </div>
      )}

      {studioTab === 'PDF_STUDIO' ? (
        <div className="grid grid-cols-1 xl:grid-cols-12 gap-4">
          {/* Left Configuration Column */}
          <div className="xl:col-span-5 bg-white dark:bg-slate-900 rounded-2xl border border-slate-200/80 dark:border-slate-800 p-4 space-y-4">
            <div className="flex items-center justify-between border-b border-slate-100 dark:border-slate-800 pb-3">
              <span className="text-xs font-bold text-slate-800 dark:text-slate-200 flex items-center gap-1.5">
                <Palette className="w-4 h-4 text-blue-600" />
                {isAr ? 'إعدادات القالب والهوية البصرية' : 'Template, Branding & Custom Notes'}
              </span>
              <span className="text-[11px] font-mono text-slate-500">
                v{currentDocVersionCount}
              </span>
            </div>

            {/* Document Type & Source Picker */}
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              <div>
                <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                  {isAr ? 'نوع المستند المحاسبي' : 'Accounting Document Type'}
                </label>
                <select
                  data-testid="pdf-doc-type-select"
                  value={documentType}
                  onChange={(e) => setDocumentType(e.target.value as AccountingPdfDocumentType)}
                  className="w-full px-3 py-2 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-xs font-semibold text-slate-900 dark:text-slate-100"
                >
                  <option value="SALES_INVOICE">
                    {isAr ? 'فاتورة مبيعات ضريبية (Sales Invoice)' : 'Tax Sales Invoice'}
                  </option>
                  <option value="TRIAL_BALANCE">
                    {isAr ? 'تقرير ميزان المراجعة (Trial Balance)' : 'Trial Balance Report'}
                  </option>
                  <option value="INCOME_STATEMENT">
                    {isAr ? 'قائمة الدخل والأرباح (Income Statement)' : 'Income Statement'}
                  </option>
                  <option value="BALANCE_SHEET">
                    {isAr ? 'المركز المالي (Balance Sheet)' : 'Balance Sheet'}
                  </option>
                  <option value="JOURNAL_VOUCHER">
                    {isAr ? 'سند قيد يومية (Journal Voucher)' : 'Journal Entry Voucher'}
                  </option>
                </select>
              </div>

              {documentType === 'SALES_INVOICE' && salesInvoices.length > 0 && (
                <div>
                  <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                    {isAr ? 'اختر الفاتورة' : 'Select Invoice'}
                  </label>
                  <select
                    data-testid="pdf-invoice-select"
                    value={selectedInvoiceId}
                    onChange={(e) => setSelectedInvoiceId(e.target.value)}
                    className="w-full px-3 py-2 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-xs font-semibold text-slate-900 dark:text-slate-100"
                  >
                    {salesInvoices.map((inv) => (
                      <option key={inv.id} value={inv.id}>
                        {inv.invoiceNumber} — {inv.customerName} ({inv.grandTotal.toLocaleString()} {currency})
                      </option>
                    ))}
                  </select>
                </div>
              )}

              {documentType === 'JOURNAL_VOUCHER' && journalEntries.length > 0 && (
                <div>
                  <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                    {isAr ? 'اختر قيد اليومية' : 'Select Journal Entry'}
                  </label>
                  <select
                    value={selectedJournalId}
                    onChange={(e) => setSelectedJournalId(e.target.value)}
                    className="w-full px-3 py-2 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-xs font-semibold text-slate-900 dark:text-slate-100"
                  >
                    {journalEntries.map((je) => (
                      <option key={je.id} value={je.id}>
                        {je.entryNumber} — {je.description}
                      </option>
                    ))}
                  </select>
                </div>
              )}
            </div>

            {/* Standard Template Cards */}
            <div>
              <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1.5">
                {isAr ? 'القوالب القياسية المعتمدة (Standard Templates)' : 'Standard Templates'}
              </label>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
                {ACCOUNTING_PDF_TEMPLATES.map((tpl) => {
                  const active = branding.templateId === tpl.id;
                  return (
                    <button
                      key={tpl.id}
                      type="button"
                      data-testid={`pdf-template-${tpl.id}`}
                      onClick={() => handleTemplateSelect(tpl.id)}
                      className={`text-start p-2.5 rounded-xl border transition cursor-pointer ${
                        active
                          ? 'border-blue-600 bg-blue-50/70 dark:bg-blue-950/30'
                          : 'border-slate-200 dark:border-slate-800 hover:border-blue-400'
                      }`}
                    >
                      <div className="flex items-center justify-between gap-2">
                        <span className="text-xs font-bold text-slate-900 dark:text-slate-100">
                          {isAr ? tpl.nameAr : tpl.nameEn}
                        </span>
                        <span
                          className="w-3.5 h-3.5 rounded-full shrink-0 border border-white shadow-2xs"
                          style={{ backgroundColor: tpl.defaultPrimary }}
                        />
                      </div>
                      <p className="text-[10.5px] text-slate-500 dark:text-slate-400 mt-1 line-clamp-1">
                        {isAr ? tpl.descriptionAr : tpl.descriptionEn}
                      </p>
                    </button>
                  );
                })}
              </div>
            </div>

            {/* Branding Colors & Logo Upload */}
            <div className="grid grid-cols-2 sm:grid-cols-3 gap-3 pt-1">
              <div>
                <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                  {isAr ? 'اللون الأساسي' : 'Primary Color'}
                </label>
                <div className="flex items-center gap-2">
                  <input
                    type="color"
                    data-testid="pdf-primary-color-input"
                    value={branding.primaryColor}
                    onChange={(e) =>
                      setBranding((prev) => ({ ...prev, primaryColor: e.target.value }))
                    }
                    className="w-8 h-8 rounded-lg border border-slate-300 cursor-pointer"
                  />
                  <span className="text-xs font-mono text-slate-700 dark:text-slate-300">
                    {branding.primaryColor}
                  </span>
                </div>
              </div>

              <div>
                <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                  {isAr ? 'لون التمييز والختم' : 'Accent Color'}
                </label>
                <div className="flex items-center gap-2">
                  <input
                    type="color"
                    data-testid="pdf-accent-color-input"
                    value={branding.accentColor}
                    onChange={(e) =>
                      setBranding((prev) => ({ ...prev, accentColor: e.target.value }))
                    }
                    className="w-8 h-8 rounded-lg border border-slate-300 cursor-pointer"
                  />
                  <span className="text-xs font-mono text-slate-700 dark:text-slate-300">
                    {branding.accentColor}
                  </span>
                </div>
              </div>

              <div className="col-span-2 sm:col-span-1">
                <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                  {isAr ? 'شعار المؤسسة (Logo)' : 'Company Logo'}
                </label>
                <label className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-xs font-semibold text-slate-700 dark:text-slate-200 cursor-pointer hover:border-blue-500">
                  <ImageIcon className="w-3.5 h-3.5 text-blue-600" />
                  <span>{isAr ? 'رفع شعار' : 'Upload Logo'}</span>
                  <input
                    type="file"
                    accept="image/*"
                    onChange={handleLogoUpload}
                    className="hidden"
                  />
                </label>
              </div>
            </div>

            {/* Custom Notes Inputs */}
            <div className="space-y-2.5">
              <div>
                <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                  {isAr ? 'ملاحظة الترويسة العلوية (Header Note)' : 'Custom Header Note'}
                </label>
                <input
                  type="text"
                  data-testid="pdf-header-note-input"
                  value={branding.headerNote || ''}
                  onChange={(e) =>
                    setBranding((prev) => ({ ...prev, headerNote: e.target.value }))
                  }
                  className="w-full px-3 py-1.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-xs text-slate-900 dark:text-slate-100"
                />
              </div>

              <div>
                <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                  {isAr ? 'الشروط والملاحظات التعاقدية (Custom Terms & Notes)' : 'Terms & Custom Notes'}
                </label>
                <textarea
                  rows={2}
                  data-testid="pdf-body-terms-input"
                  value={branding.bodyTermsNote || ''}
                  onChange={(e) =>
                    setBranding((prev) => ({ ...prev, bodyTermsNote: e.target.value }))
                  }
                  className="w-full px-3 py-1.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-xs text-slate-900 dark:text-slate-100"
                />
              </div>

              <div>
                <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                  {isAr ? 'بيانات الحساب البنكي (IBAN / Bank Note)' : 'Bank Details Note'}
                </label>
                <input
                  type="text"
                  value={branding.bankDetailsNote || ''}
                  onChange={(e) =>
                    setBranding((prev) => ({ ...prev, bankDetailsNote: e.target.value }))
                  }
                  className="w-full px-3 py-1.5 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-xs font-mono text-slate-900 dark:text-slate-100"
                />
              </div>
            </div>

            {/* Action Buttons: Print PDF, Download PDF HTML, Save Version Snapshot */}
            <div className="pt-2 border-t border-slate-100 dark:border-slate-800 space-y-2">
              <div className="flex flex-wrap items-center gap-2">
                <button
                  type="button"
                  data-testid="pdf-print-btn"
                  onClick={() => printAccountingPdfHtml(generatedPdf.htmlContent)}
                  className="flex-1 inline-flex items-center justify-center gap-1.5 px-3.5 py-2.5 rounded-xl bg-blue-600 hover:bg-blue-700 text-white text-xs font-bold transition cursor-pointer"
                >
                  <Printer className="w-4 h-4" />
                  <span>{isAr ? 'طباعة / تصدير PDF' : 'Print / Export PDF'}</span>
                </button>

                <button
                  type="button"
                  data-testid="pdf-download-btn"
                  onClick={() => downloadAccountingPdfHtmlSnapshot(generatedPdf)}
                  className="inline-flex items-center justify-center gap-1.5 px-3.5 py-2.5 rounded-xl bg-slate-900 dark:bg-slate-800 hover:bg-slate-800 text-white text-xs font-bold transition cursor-pointer"
                >
                  <Download className="w-4 h-4" />
                  <span>{isAr ? 'تنزيل النسخة' : 'Download'}</span>
                </button>
              </div>

              <div className="flex items-center gap-2">
                <input
                  type="text"
                  data-testid="version-reason-input"
                  placeholder={
                    isAr
                      ? 'سبب حفظ الإصدار الجديد (مثال: تعديل الخصم أو القالب)...'
                      : 'Version snapshot reason...'
                  }
                  value={changeReasonInput}
                  onChange={(e) => setChangeReasonInput(e.target.value)}
                  className="flex-1 px-3 py-2 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800 text-xs text-slate-900 dark:text-slate-100"
                />
                <button
                  type="button"
                  data-testid="save-doc-version-btn"
                  onClick={handleSaveNewVersionSnapshot}
                  className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-emerald-600 hover:bg-emerald-700 text-white text-xs font-bold transition cursor-pointer shrink-0"
                >
                  <Save className="w-3.5 h-3.5" />
                  <span>{isAr ? 'حفظ كإصدار مؤرشف' : 'Save Version'}</span>
                </button>
              </div>
            </div>
          </div>

          {/* Right Live Preview Column */}
          <div className="xl:col-span-7 bg-white dark:bg-slate-900 rounded-2xl border border-slate-200/80 dark:border-slate-800 p-4 flex flex-col">
            <div className="flex items-center justify-between pb-3 mb-3 border-b border-slate-100 dark:border-slate-800">
              <div className="flex items-center gap-2 text-xs font-bold text-slate-800 dark:text-slate-200">
                <Eye className="w-4 h-4 text-blue-600" />
                <span>
                  {isAr
                    ? `معاينة حية للمستند المالي (${generatedPdf.referenceNumber})`
                    : `Live PDF Document Preview (${generatedPdf.referenceNumber})`}
                </span>
              </div>
              <span className="text-[11px] font-mono px-2 py-0.5 rounded bg-blue-50 dark:bg-blue-950/60 text-blue-700 dark:text-blue-300">
                {branding.templateId} · {branding.paperSize}
              </span>
            </div>

            <div className="flex-1 min-h-[540px] rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-100 dark:bg-slate-950 p-2 overflow-hidden">
              <iframe
                data-testid="accounting-pdf-preview-iframe"
                title="Accounting PDF Document Preview"
                srcDoc={generatedPdf.htmlContent}
                className="w-full h-[540px] rounded-lg bg-white border-0"
              />
            </div>
          </div>
        </div>
      ) : (
        /* Document Versioning System Tab: History List + Side-by-Side Comparison + 1-Click Restore */
        <div
          data-testid="accounting-versioning-panel"
          className="grid grid-cols-1 xl:grid-cols-12 gap-4"
        >
          {/* Left: Version Timeline & Restore Actions */}
          <div className="xl:col-span-5 bg-white dark:bg-slate-900 rounded-2xl border border-slate-200/80 dark:border-slate-800 p-4 space-y-3">
            <div className="flex items-center justify-between border-b border-slate-100 dark:border-slate-800 pb-3">
              <div className="flex items-center gap-2 text-xs font-bold text-slate-900 dark:text-slate-100">
                <History className="w-4 h-4 text-blue-600" />
                <span>
                  {isAr
                    ? 'سجل إصدارات الفواتير والتقارير المالية'
                    : 'Saved Invoice & Financial Report Versions'}
                </span>
              </div>
              <button
                type="button"
                onClick={handleSaveNewVersionSnapshot}
                className="inline-flex items-center gap-1 px-2.5 py-1 rounded-lg bg-blue-600 text-white text-[11px] font-bold cursor-pointer"
              >
                <Sparkles className="w-3 h-3" />
                <span>{isAr ? '+ لقطة إصدار جديدة' : '+ Snapshot Current'}</span>
              </button>
            </div>

            <div className="space-y-2.5 max-h-[540px] overflow-y-auto pr-1">
              {versions.map((ver) => {
                const isBase = ver.versionId === selectedBaseVersionId;
                const isTarget = ver.versionId === selectedTargetVersionId;
                return (
                  <div
                    key={ver.versionId}
                    data-testid={`doc-version-card-v${ver.versionNumber}-${ver.payload.referenceNumber}`}
                    className={`p-3 rounded-xl border transition space-y-2 ${
                      isTarget
                        ? 'border-blue-600 bg-blue-50/50 dark:bg-blue-950/25'
                        : isBase
                        ? 'border-amber-500 bg-amber-50/40 dark:bg-amber-950/20'
                        : 'border-slate-200 dark:border-slate-800 bg-slate-50/50 dark:bg-slate-950/40'
                    }`}
                  >
                    <div className="flex items-center justify-between gap-2">
                      <div className="flex items-center gap-2">
                        <span className="px-2 py-0.5 rounded-md bg-slate-900 dark:bg-slate-700 text-white font-mono text-[11px] font-bold">
                          v{ver.versionNumber}
                        </span>
                        <span className="text-xs font-bold text-slate-900 dark:text-slate-100">
                          {ver.payload.referenceNumber}
                        </span>
                        <span className="text-[10px] font-mono text-slate-500">
                          {ver.checksum}
                        </span>
                      </div>
                      <span className="text-xs font-bold font-mono text-blue-700 dark:text-blue-400">
                        {ver.payload.grandTotal.toLocaleString()} {currency}
                      </span>
                    </div>

                    <div className="text-xs font-semibold text-slate-700 dark:text-slate-300">
                      {ver.payload.customerOrTitle}
                    </div>
                    <div className="text-[11px] text-slate-500 dark:text-slate-400">
                      {ver.changeReason}
                    </div>

                    <div className="flex flex-wrap items-center justify-between gap-2 pt-2 border-t border-slate-200/60 dark:border-slate-800 text-[11px]">
                      <span className="text-slate-500">
                        {ver.createdBy} · {ver.createdAtIso.slice(0, 10)}
                      </span>

                      <div className="flex items-center gap-1.5">
                        <button
                          type="button"
                          onClick={() => setSelectedBaseVersionId(ver.versionId)}
                          className={`px-2 py-1 rounded-md font-semibold cursor-pointer ${
                            isBase
                              ? 'bg-amber-500 text-white'
                              : 'bg-slate-200 dark:bg-slate-800 text-slate-700 dark:text-slate-300'
                          }`}
                        >
                          {isAr ? 'كأساس مقارنة (Base)' : 'Set Base'}
                        </button>

                        <button
                          type="button"
                          onClick={() => setSelectedTargetVersionId(ver.versionId)}
                          className={`px-2 py-1 rounded-md font-semibold cursor-pointer ${
                            isTarget
                              ? 'bg-blue-600 text-white'
                              : 'bg-slate-200 dark:bg-slate-800 text-slate-700 dark:text-slate-300'
                          }`}
                        >
                          {isAr ? 'مقارنة مع (Target)' : 'Set Target'}
                        </button>

                        <button
                          type="button"
                          data-testid={`restore-version-btn-v${ver.versionNumber}`}
                          onClick={() => handleRestoreVersion(ver)}
                          className="inline-flex items-center gap-1 px-2.5 py-1 rounded-md bg-emerald-600 hover:bg-emerald-700 text-white font-bold cursor-pointer"
                        >
                          <RotateCcw className="w-3 h-3" />
                          <span>{isAr ? 'استعادة' : 'Restore'}</span>
                        </button>
                      </div>
                    </div>
                  </div>
                );
              })}
            </div>
          </div>

          {/* Right: Side-by-Side Diff Comparison Viewer */}
          <div
            data-testid="version-diff-comparison-viewer"
            className="xl:col-span-7 bg-white dark:bg-slate-900 rounded-2xl border border-slate-200/80 dark:border-slate-800 p-4 space-y-4"
          >
            <div className="flex flex-wrap items-center justify-between gap-2 border-b border-slate-100 dark:border-slate-800 pb-3">
              <div className="flex items-center gap-2 text-xs font-bold text-slate-900 dark:text-slate-100">
                <GitCompare className="w-4 h-4 text-blue-600" />
                <span>
                  {isAr
                    ? 'مقارنة الفروقات التفصيلية بين الإصدارين (Side-by-Side Version Diff)'
                    : 'Side-by-Side Version Comparison & Audit Diff'}
                </span>
              </div>

              {comparisonResult && (
                <div className="flex items-center gap-2 text-xs font-mono">
                  <span className="px-2 py-0.5 rounded bg-amber-100 dark:bg-amber-950/60 text-amber-800 dark:text-amber-300 font-bold">
                    Base: v{comparisonResult.baseVersion.versionNumber}
                  </span>
                  <span>→</span>
                  <span className="px-2 py-0.5 rounded bg-blue-100 dark:bg-blue-950/60 text-blue-800 dark:text-blue-300 font-bold">
                    Target: v{comparisonResult.targetVersion.versionNumber}
                  </span>
                  <span className="px-2 py-0.5 rounded bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300">
                    {comparisonResult.changedFieldsCount}{' '}
                    {isAr ? 'تغييرات مكتشفة' : 'diffs'}
                  </span>
                </div>
              )}
            </div>

            {comparisonResult ? (
              <div className="space-y-4">
                {/* Summary KPI Delta Strip */}
                <div className="grid grid-cols-3 gap-3 p-3 rounded-xl bg-slate-50 dark:bg-slate-950/60 border border-slate-200/70 dark:border-slate-800">
                  <div>
                    <div className="text-[11px] text-slate-500">
                      {isAr ? 'النسخة الأساسية (Base)' : 'Base Version Total'}
                    </div>
                    <div className="text-sm font-bold font-mono text-slate-900 dark:text-slate-100">
                      {comparisonResult.baseVersion.payload.grandTotal.toLocaleString()} {currency}
                    </div>
                  </div>
                  <div>
                    <div className="text-[11px] text-slate-500">
                      {isAr ? 'النسخة المقارنة (Target)' : 'Target Version Total'}
                    </div>
                    <div className="text-sm font-bold font-mono text-blue-700 dark:text-blue-400">
                      {comparisonResult.targetVersion.payload.grandTotal.toLocaleString()} {currency}
                    </div>
                  </div>
                  <div>
                    <div className="text-[11px] text-slate-500">
                      {isAr ? 'صافي الفرق المالي (Delta)' : 'Net Financial Delta'}
                    </div>
                    <div
                      className={`text-sm font-bold font-mono ${
                        comparisonResult.totalAmountDelta > 0
                          ? 'text-emerald-600'
                          : comparisonResult.totalAmountDelta < 0
                          ? 'text-red-600'
                          : 'text-slate-600'
                      }`}
                    >
                      {comparisonResult.totalAmountDelta > 0 ? '+' : ''}
                      {comparisonResult.totalAmountDelta.toLocaleString()} {currency}
                    </div>
                  </div>
                </div>

                {/* Field-Level Diffs Table */}
                <div className="overflow-x-auto rounded-xl border border-slate-200 dark:border-slate-800">
                  <table className="w-full text-xs border-collapse">
                    <thead>
                      <tr className="bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300">
                        <th className="p-2.5 text-start">{isAr ? 'الحقل المحاسبي' : 'Field'}</th>
                        <th className="p-2.5 text-start">
                          {isAr
                            ? `الإصدار v${comparisonResult.baseVersion.versionNumber} (السابق)`
                            : `Base (v${comparisonResult.baseVersion.versionNumber})`}
                        </th>
                        <th className="p-2.5 text-start">
                          {isAr
                            ? `الإصدار v${comparisonResult.targetVersion.versionNumber} (الحالي)`
                            : `Target (v${comparisonResult.targetVersion.versionNumber})`}
                        </th>
                        <th className="p-2.5 text-center">{isAr ? 'الحالة' : 'Diff'}</th>
                      </tr>
                    </thead>
                    <tbody>
                      {comparisonResult.fieldDiffs.map((fd) => (
                        <tr
                          key={fd.fieldKey}
                          className={`border-t border-slate-100 dark:border-slate-800 ${
                            fd.changed
                              ? 'bg-amber-50/50 dark:bg-amber-950/20 font-semibold'
                              : ''
                          }`}
                        >
                          <td className="p-2.5 text-slate-700 dark:text-slate-300">
                            {isAr ? fd.labelAr : fd.labelEn}
                          </td>
                          <td className="p-2.5 font-mono text-slate-600 dark:text-slate-400">
                            {String(fd.previousValue)}
                          </td>
                          <td className="p-2.5 font-mono text-slate-900 dark:text-slate-100">
                            {String(fd.currentValue)}
                          </td>
                          <td className="p-2.5 text-center">
                            {fd.changed ? (
                              <span className="px-2 py-0.5 rounded bg-amber-200/80 dark:bg-amber-900/60 text-amber-900 dark:text-amber-200 text-[10px] font-bold">
                                {fd.deltaNumeric !== undefined && fd.deltaNumeric !== 0
                                  ? `${fd.deltaNumeric > 0 ? '+' : ''}${fd.deltaNumeric.toLocaleString()}`
                                  : isAr
                                  ? 'مُعدّل'
                                  : 'MODIFIED'}
                              </span>
                            ) : (
                              <span className="text-[10px] text-slate-400">
                                {isAr ? 'مطابق' : 'Identical'}
                              </span>
                            )}
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>

                {/* Line Items Diff Table */}
                <div>
                  <h4 className="text-xs font-bold text-slate-800 dark:text-slate-200 mb-2">
                    {isAr ? 'مقارنة بنود المستند والحسابات التفصيلية' : 'Line Item & Ledger Row Diffs'}
                  </h4>
                  <div className="overflow-x-auto rounded-xl border border-slate-200 dark:border-slate-800">
                    <table className="w-full text-xs border-collapse">
                      <thead>
                        <tr className="bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300">
                          <th className="p-2 text-start">{isAr ? 'الكود' : 'Code'}</th>
                          <th className="p-2 text-start">{isAr ? 'البيان' : 'Description'}</th>
                          <th className="p-2 text-end">{isAr ? 'قيمة الأساس' : 'Base Total'}</th>
                          <th className="p-2 text-end">{isAr ? 'القيمة المقارنة' : 'Target Total'}</th>
                          <th className="p-2 text-center">{isAr ? 'التغيير' : 'Status'}</th>
                        </tr>
                      </thead>
                      <tbody>
                        {comparisonResult.lineDiffs.map((ld, idx) => (
                          <tr
                            key={`${ld.code}-${idx}`}
                            className="border-t border-slate-100 dark:border-slate-800"
                          >
                            <td className="p-2 font-mono">{ld.code}</td>
                            <td className="p-2 font-semibold">{ld.label}</td>
                            <td className="p-2 text-end font-mono">{ld.baseTotal.toLocaleString()}</td>
                            <td className="p-2 text-end font-mono font-bold">
                              {ld.targetTotal.toLocaleString()}
                            </td>
                            <td className="p-2 text-center">
                              <span
                                className={`px-2 py-0.5 rounded text-[10px] font-bold ${
                                  ld.status === 'ADDED'
                                    ? 'bg-emerald-100 text-emerald-800 dark:bg-emerald-950/60 dark:text-emerald-300'
                                    : ld.status === 'REMOVED'
                                    ? 'bg-red-100 text-red-800 dark:bg-red-950/60 dark:text-red-300'
                                    : ld.status === 'MODIFIED'
                                    ? 'bg-amber-100 text-amber-800 dark:bg-amber-950/60 dark:text-amber-300'
                                    : 'bg-slate-100 text-slate-600 dark:bg-slate-800 dark:text-slate-400'
                                }`}
                              >
                                {ld.status}
                              </span>
                            </td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                </div>
              </div>
            ) : null}
          </div>
        </div>
      )}
    </div>
  );
};

export default AccountingPdfAndVersioningStudio;
