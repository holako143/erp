/**
 * Builds the zero-download offline portable bundle AND native Windows (.exe) installer for Haseb ERP:
 * 1. Packages compiled VitePWA `dist/` files into `bundle/embeddedDistAssets.ts` (gzip+base64).
 * 2. Compiles full unified `server.ts` into `bundle/server.bundle.cjs` (CJS, zero runtime node_modules).
 * 3. Cross-compiles `windows_exe_entry.ts` into native Windows PE64 `bundle/Haseb_ERP_Setup_Offline.exe` via Bun.
 * 4. Syncs `installer_windows.bat`, `installer_linux_mac.sh`, and `bundle/README_SETUP_AR.txt`.
 */

import fs from 'fs';
import path from 'path';
import zlib from 'zlib';
import { execFileSync } from 'child_process';
import * as esbuild from 'esbuild';
import {
  generateLinuxMacSetupSh,
  generatePortableReadmeAr,
  generateWindowsSetupBat,
} from '../src/core/installerEngine';

const MIME_BY_EXT: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.mjs': 'application/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.woff': 'font/woff',
  '.ttf': 'font/ttf',
  '.txt': 'text/plain; charset=utf-8',
};

function resolveMimeType(fileName: string): string {
  const ext = path.extname(fileName).toLowerCase();
  return MIME_BY_EXT[ext] || 'application/octet-stream';
}

function collectCompressedDistMap(
  distDir: string
): Record<string, { mime: string; gzB64: string }> {
  const map: Record<string, { mime: string; gzB64: string }> = {};
  if (!fs.existsSync(distDir)) return map;

  const walk = (currDir: string, relPrefix: string) => {
    const entries = fs.readdirSync(currDir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(currDir, entry.name);
      const relPath = relPrefix ? `${relPrefix}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        walk(fullPath, relPath);
      } else if (entry.isFile()) {
        const raw = fs.readFileSync(fullPath);
        const gz = zlib.gzipSync(raw, { level: 9 });
        map[relPath.replace(/\\/g, '/')] = {
          mime: resolveMimeType(entry.name),
          gzB64: gz.toString('base64'),
        };
      }
    }
  };
  walk(distDir, '');
  return map;
}

async function main() {
  const rootDir = process.cwd();
  const bundleDir = path.join(rootDir, 'bundle');
  const distDir = path.join(rootDir, 'dist');
  if (!fs.existsSync(bundleDir)) {
    fs.mkdirSync(bundleDir, { recursive: true });
  }

  // 1. Embed compiled dist/ assets into TypeScript module for standalone .exe
  const embeddedMap = collectCompressedDistMap(distDir);
  const embeddedTsPath = path.join(bundleDir, 'embeddedDistAssets.ts');
  const embeddedCount = Object.keys(embeddedMap).length;
  fs.writeFileSync(
    embeddedTsPath,
    `// Auto-generated by scripts/build_portable_bundle.ts (${embeddedCount} files)\nexport const EMBEDDED_DIST_ASSETS: Record<string, { mime: string; gzB64: string }> = ${JSON.stringify(
      embeddedMap
    )};\n`,
    'utf8'
  );
  console.log(`[Portable Bundle] Embedded ${embeddedCount} dist/ assets into ${embeddedTsPath}`);

  // 2. Compile full server.ts -> bundle/server.bundle.cjs
  const outFile = path.join(bundleDir, 'server.bundle.cjs');
  await esbuild.build({
    entryPoints: [path.join(rootDir, 'server.ts')],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: ['node22'],
    external: ['vite', 'esbuild', 'playwright', 'node:sqlite'],
    define: {
      'import.meta.url': '__filename',
    },
    outfile: outFile,
    minify: false,
    logLevel: 'info',
  });

  // 3. Cross-compile native Windows PE64 .exe via Bun when available
  const exeOutFile = path.join(bundleDir, 'Haseb_ERP_Setup_Offline.exe');
  try {
    execFileSync(
      'bun',
      [
        'build',
        path.join(rootDir, 'windows_exe_entry.ts'),
        '--compile',
        '--target=bun-windows-x64',
        '--external',
        'vite',
        '--external',
        'esbuild',
        '--external',
        'playwright',
        '--outfile',
        exeOutFile,
      ],
      { stdio: 'inherit', timeout: 120000 }
    );
    if (fs.existsSync(exeOutFile)) {
      const exeStat = fs.statSync(exeOutFile);
      console.log(
        `[Portable Bundle] Built native Windows EXE: ${exeOutFile} (${(
          exeStat.size /
          (1024 * 1024)
        ).toFixed(1)} MB)`
      );
    }
  } catch (err: any) {
    console.warn(
      '[Portable Bundle] Bun Windows .exe compilation skipped/failed:',
      err?.message || err
    );
  }

  // 4. Sync scripts & Arabic README
  fs.writeFileSync(
    path.join(rootDir, 'installer_windows.bat'),
    generateWindowsSetupBat({ port: 3000, httpsPort: 3443 }),
    'utf8'
  );
  fs.writeFileSync(
    path.join(rootDir, 'installer_linux_mac.sh'),
    generateLinuxMacSetupSh({ port: 3000, httpsPort: 3443 }),
    'utf8'
  );
  fs.chmodSync(path.join(rootDir, 'installer_linux_mac.sh'), 0o755);
  fs.writeFileSync(
    path.join(bundleDir, 'README_SETUP_AR.txt'),
    generatePortableReadmeAr({ port: 3000, httpsPort: 3443 }),
    'utf8'
  );

  const stat = fs.statSync(outFile);
  console.log(
    `[Portable Bundle] Built ${outFile} (${(stat.size / 1024).toFixed(1)} KB) + installers ready.`
  );
}

main().catch((err) => {
  console.error('[Portable Bundle] Build failed:', err);
  process.exit(1);
});
